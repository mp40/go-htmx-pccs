DROP TABLE IF EXISTS firearm_magazine;
DROP TABLE IF EXISTS firearm_ammo_range;
DROP TABLE IF EXISTS firearm_ammo;
DROP TABLE IF EXISTS firearm_ballistics_range;
DROP TABLE IF EXISTS firearm;
DROP TABLE IF EXISTS magazine;
DROP TABLE IF EXISTS aim_time;

CREATE TABLE aim_time (
    id    INTEGER PRIMARY KEY NOT NULL,
    at_1  INTEGER NOT NULL,
    at_2  INTEGER NOT NULL,
    at_3  INTEGER NOT NULL,
    at_4  INTEGER NOT NULL,
    at_5  INTEGER,
    at_6  INTEGER,
    at_7  INTEGER,
    at_8  INTEGER,
    at_9  INTEGER,
    at_10 INTEGER,
    at_11 INTEGER,
    at_12 INTEGER
);

CREATE TABLE firearm (
    id                  INTEGER PRIMARY KEY NOT NULL,
    name                TEXT UNIQUE NOT NULL,
    calibre             TEXT NOT NULL,
    base_weight         REAL NOT NULL,
    length              REAL NOT NULL,
    length_stock_folded REAL,
    internal_capacity   INTEGER CHECK (internal_capacity IS NULL OR internal_capacity > 0), -- NULL = detachable magazine only
    round_weight        REAL    CHECK (round_weight IS NULL OR round_weight > 0),          -- per loose round, from card AW when feed is Rnd
    reload_time         INTEGER NOT NULL,
    manual_cycle_time   INTEGER,
    semi_automatic      BOOLEAN NOT NULL CHECK (semi_automatic IN (0, 1)),
    burst_rounds        INTEGER,
    full_auto_rof       INTEGER,
    knock_down          INTEGER NOT NULL,
    sab                 INTEGER NOT NULL,
    aim_time_id         INTEGER NOT NULL REFERENCES aim_time(id)
);

CREATE TABLE firearm_ammo (
    id INTEGER PRIMARY KEY NOT NULL,
    firearm_id      INTEGER NOT NULL REFERENCES firearm(id),
    type            TEXT NOT NULL,
    UNIQUE (firearm_id, type)
);

CREATE TABLE firearm_ballistics_range (
    firearm_id  INTEGER NOT NULL REFERENCES firearm(id),
    range_hexes INTEGER NOT NULL CHECK (range_hexes > 0),
    ba          INTEGER NOT NULL,
    tof         INTEGER NOT NULL,
    ma          REAL,
    PRIMARY KEY (firearm_id, range_hexes)
);

CREATE TABLE firearm_ammo_range (
    firearm_ammo_id INTEGER NOT NULL REFERENCES firearm_ammo(id),
    range_hexes     INTEGER NOT NULL CHECK (range_hexes > 0),
    pen             REAL    NOT NULL,
    dc              INTEGER NOT NULL,
    salm            INTEGER,
    bphc            INTEGER,
    bphc_hits       INTEGER,
    pr              REAL,
    PRIMARY KEY (firearm_ammo_id, range_hexes),
    CHECK ((salm IS NULL) = (pr IS NULL))
);

CREATE TABLE magazine (
    id        INTEGER PRIMARY KEY NOT NULL,
    name      TEXT    NOT NULL, -- magazine family, e.g. 'M1911A1', later 'STANAG'
    feed_type TEXT    NOT NULL CHECK (feed_type IN ('Mag', 'Drm', 'Blt', 'CS', 'Cp', 'SL', 'HMC')),
    capacity  INTEGER NOT NULL CHECK (capacity > 0),
    weight    REAL    NOT NULL CHECK (weight > 0), -- loaded
    UNIQUE (name, capacity, feed_type)
);

CREATE TABLE firearm_magazine (
    firearm_id  INTEGER NOT NULL REFERENCES firearm(id),
    magazine_id INTEGER NOT NULL REFERENCES magazine(id),
    PRIMARY KEY (firearm_id, magazine_id)
);

